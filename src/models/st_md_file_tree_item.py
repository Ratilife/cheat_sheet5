class STMDFileTreeItem:
    """
        Элемент дерева для представления структуры ST и MD файлов.

        Класс представляет узел в иерархической структуре дерева файлов, используемой
        моделью STMDFileTreeModel для отображения содержимого ST-файлов (Structured Text)
        и MD-файлов (Markdown) в виде древовидной структуры.

        Каждый элемент содержит:
        - Данные элемента (имя, тип, контент)
        - Ссылку на родительский элемент для навигации вверх по дереву
        - Список дочерних элементов для представления вложенной структуры

        Структура данных (item_data):
            [0] - Имя элемента (str): отображаемое имя файла, папки или шаблона
            [1] - Тип элемента (str): 'file', 'folder', 'template', 'markdown'
            [2] - Контент (str): содержимое элемента (путь к файлу для файловых элементов,
                                 текст шаблона для шаблонов, пустая строка для папок)

        Используется в:
            - STMDFileTreeModel для построения иерархической модели данных
            - Отображении структуры файлов в боковой панели приложения
            - Навигации по вложенным элементам (папки, шаблоны, файлы)
            - Редактировании структуры файлов через UI

        Attributes:
            item_data (list): Список данных элемента [имя, тип, контент]
            parent_item (STMDFileTreeItem | None): Родительский элемент дерева
            child_items (list[STMDFileTreeItem]): Список дочерних элементов
            type (str): Тип элемента, извлеченный из item_data[1] для удобного доступа
        """
    def __init__(self, data, parent=None):
        self.item_data = data  # [Имя, Тип, Контент]
        self.parent_item = parent  # Родительская ветка
        self.child_items = []  # Дочерние элементы
        # Cвойство для доступа к типу
        self.type = data[1] if len(data) > 1 else ""